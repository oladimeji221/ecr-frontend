<script setup>
import { ref, onMounted, nextTick } from 'vue';

onMounted(async () => {
  await nextTick();
  
  // Wait for main.js to be available and initialize fancy text
  const initFancyText = () => {
    const fancyTextElement = document.querySelector('[data-fancy-text]');
    if (fancyTextElement && typeof window !== 'undefined') {
      // Check if jQuery and FancyTextDefault are available
      if (window.$ && window.FancyTextDefault) {
        const ftOptions = fancyTextElement.getAttribute('data-fancy-text');
        if (ftOptions) {
          try {
            const options = JSON.parse(ftOptions);
            window.FancyTextDefault(fancyTextElement, options);
          } catch (e) {
            console.error('Error parsing fancy text options:', e);
            // Fallback: show the text anyway
            fancyTextElement.style.opacity = '1';
            fancyTextElement.textContent = 'ECR TECHNOLOGY SERVICES';
          }
        }
      } else {
        // Fallback if main.js isn't loaded: show the text directly
        setTimeout(() => {
          if (fancyTextElement.style.opacity === '0' || !fancyTextElement.textContent) {
            fancyTextElement.style.opacity = '1';
            fancyTextElement.style.transform = 'none';
            fancyTextElement.style.filter = 'none';
            fancyTextElement.textContent = 'ECR TECHNOLOGY SERVICES';
          }
        }, 1000);
      }
    }
  };

  // Try multiple times in case main.js loads later
  initFancyText();
  setTimeout(initFancyText, 500);
  setTimeout(initFancyText, 1500);
  setTimeout(initFancyText, 3000);
});

</script>
