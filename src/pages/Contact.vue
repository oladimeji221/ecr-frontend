<script setup>
import { ref } from 'vue';
import api from '../services/api';
import { useSeo, localBusinessSchema } from '@/composables/useSeo';

useSeo({
  title: 'Contact Us - Get In Touch',
  description: 'Contact ECR Technology Services. Reach us at our Umuahia, Nigeria office or by phone/email. We are here to help you with your IT and digital transformation needs.',
  url: 'https://www.ecr-ts.com/contact',
  schema: localBusinessSchema
});

const formData = ref({
    name: '',
    email: '',
    message: ''
});

const status = ref({
    success: '',
    error: ''
});

const loading = ref(false);

const submitContactForm = async () => {
    // Validate required fields
    if (!formData.value.name || !formData.value.email || !formData.value.message) {
        status.value.error = 'Please fill in all required fields.';
        return;
    }

    status.value = { success: '', error: '' };
    loading.value = true;

    try {
        const payload = {
            name: formData.value.name,
            email: formData.value.email,
            message: formData.value.message
        };

        const response = await api.post('/contact', payload);

        status.value.success = response.data.message || 'Your message has been sent successfully!';
        formData.value = { name: '', email: '', message: '' };
    } catch (error) {
        console.error('Contact form error:', error);
        console.error('Error response:', error.response);
        console.error('Error status:', error.response?.status);
        console.error('Error URL:', error.config?.url);
        
        if (error.response?.status === 404) {
            status.value.error = 'API endpoint not found (404). Please ensure the backend server is running on http://localhost:8000 and the /api/contact route exists.';
        } else if (error.response?.status === 0 || !error.response) {
            status.value.error = 'Cannot connect to server. Please check if the backend is running on http://localhost:8000';
        } else if (error.response?.data?.errors) {
            status.value.error = Object.values(error.response.data.errors).flat().join(' ');
        } else if (error.response?.data?.message) {
            status.value.error = error.response.data.message;
        } else if (error.message) {
            status.value.error = error.message;
        } else {
            status.value.error = 'Failed to send message. Please check your connection and try again.';
        }
    } finally {
        loading.value = false;
    }
};
</script>

